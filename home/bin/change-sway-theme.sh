# Theme name: if provided as first arg, use it; otherwise prompt with rofi
if [ $# -ge 1 ]; then
	THEME_NAME="$1"
else
	if command -v rofi >/dev/null 2>&1; then
		selection=$(printf "%s\n" "$THEME_LIST" | sed '/^\s*$/d' | rofi -dmenu -i -p "Theme")
		if [ -z "$selection" ]; then
			echo "No theme selected; exiting."
			exit 1
		fi
		THEME_NAME="$selection"
	else
		THEME_NAME="default-dark"
	fi
fi


# Respect XDG_CONFIG_HOME if set, otherwise use ~/.config
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/sway/config.d"
OUT_FILE="$CONFIG_DIR/colorscheme.conf"
URL="https://raw.githubusercontent.com/rkubosz/base16-sway/master/themes/base16-${THEME_NAME}.config"

mkdir -p "$CONFIG_DIR"
curl -fsSL "$URL" -o "$OUT_FILE"
echo "Wrote theme '$THEME_NAME' to $OUT_FILE"
